"""Build auditable tables from the actual calculation checkpoints.

Run from the repository root after benchmark and refinement calculations:
    python benchmarks/report.py
The repository contains compact summaries. The delivery archive additionally
contains complete checkpoints, spectra and per-time diagnostics.
"""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results"
thermal = json.loads((OUT / "screening/thermal.json").read_text())
packets = json.loads((OUT / "screening/packets.json").read_text())
refinement = json.loads((OUT / "refinement/checks.json").read_text())


def write_csv(name, rows):
    with (OUT / name).open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


rows = []
for kind, item in thermal["models"].items():
    for beta, runs in item["rpmd"].items():
        for dimension, run in runs.items():
            rows.append(dict(model=kind, beta=beta, dimension=dimension,
                             qd_rate=item["qd"][dimension]["rates"][beta],
                             rpmd_rate=run["rate"], rpmd_stderr=run["stderr"],
                             importance_ess=run["importance_ess"], samples=run["samples"],
                             beads=run["beads"], dt=run["dt"], time=run["time"], seed=run["seed"],
                             warnings=";".join(run["warnings"])))
write_csv("thermal_summary.csv", rows)
corrections = []
for kind, item in thermal["models"].items():
    for beta, runs in item["corrections"].items():
        reference = item["qd"]["3D"]["rates"][beta]
        for dimension, run in runs.items():
            corrections.append(dict(model=kind, beta=beta, correction_dimension=dimension,
                qd_3d=reference, corrected_rate=run["rate"], stderr=run["stderr_delta_method"],
                factor=run["factor"], relative_error_percent=100*(run["rate"]/reference-1),
                warnings=";".join(run["warnings"])))
write_csv("correction_summary.csv", corrections)
rows = []
for kind, item in packets["models"].items():
    for method, run in item["methods"].items():
        rows.append(dict(model=kind, method=method, product_probability=run["product_probability"],
                         stderr=run["stderr"], time=run["config"]["time"],
                         interaction_probability=run["trace"][-1]["interaction"],
                         x_edge_probability=run["max_x_edge_probability"],
                         energy_drift=run["max_relative_energy_drift"],
                         initial_thermal_omitted_weight=run["initial_thermal_omitted_weight"],
                         warnings=";".join(run["warnings"])))
write_csv("packet_summary.csv", rows)
compact = {key: value for key, value in refinement.items() if key not in ("rpmd", "packets", "metadata")}
compact["refined_rpmd_tunneling_beta2"] = {key: value for key, value in refinement["rpmd"]["tunneling_beta2"].items()
                                         if key not in ("times", "kappa", "rate_trace")}
compact["refined_packet_tunneling"] = {key: value for key, value in refinement["packets"]["tunneling_QD3D"].items()
                                     if key != "trace"}
(OUT / "refinement_summary.json").write_text(json.dumps(compact, indent=2) + "\n")
manifest = {"note": "Complete raw files are included in the delivered archive and regenerated by the documented CLI; compact summaries are committed.",
            "files": {}}
for path in sorted(list((OUT / "screening").glob("*")) + list((OUT / "refinement").glob("*.json"))):
    if path.is_file():
        content = path.read_bytes()
        manifest["files"][str(path.relative_to(ROOT))] = {
            "bytes": len(content), "sha256": hashlib.sha256(content).hexdigest()}
(OUT / "raw_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
